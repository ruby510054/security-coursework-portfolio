def compute_rotate_amount(idx: int) -> int:
    temp = (idx * 0x25) & 0xFFFF
    r10 = (temp >> 8) & 0xFF
    r9 = ((idx - r10) >> 1) + r10
    r9 = r9 >> 2
    r9 = (r9 * 8) - r9  # 7 * r9
    rotate_amount = (idx - r9 + 1) & 0x07
    return rotate_amount

def ror8(val: int, r: int) -> int:
    r = r & 0x7
    if r == 0:
        return val & 0xFF
    return ((val >> r) | ((val << (8 - r)) & 0xFF)) & 0xFF

def decrypt(cipher_bytes: List[int], input_len: int) -> bytes:
    recovered = [0] * (max(permutation_table)+1)
    for pos in range(input_len):
        perm_idx = permutation_table[pos]
        enc = cipher_bytes[pos]
        rot = compute_rotate_amount(perm_idx)
        xored = ror8(enc, rot)
        print(f"len(recovered)={len(recovered)}, perm_idx={perm_idx}")
        ch = xored ^ xor_table[perm_idx]
        recovered[perm_idx] = ch
    return bytes(recovered)

